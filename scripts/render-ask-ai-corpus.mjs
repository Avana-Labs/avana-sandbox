import { createHash } from "node:crypto"
import { readFileSync } from "node:fs"
import { resolve } from "node:path"

const SOURCES = [
  {
    id: "avana-whitepaper",
    title: "Avana Whitepaper",
    kind: "whitepaper",
    path: "convex/knowledge/avana-whitepaper.md",
    url: "/whitepaper",
  },
  {
    id: "avana-developer-documentation",
    title: "Avana Developer Documentation",
    kind: "developer_docs",
    path: "convex/knowledge/avana-developer-documentation.md",
    url: "/developers/introduction",
  },
  {
    id: "avana-faq",
    title: "Avana FAQ",
    kind: "faq",
    path: "convex/knowledge/avana-faq.md",
    url: "/faq",
  },
]

const MAX_CHARS = 3_600
const hash = (value) => createHash("sha256").update(value).digest("hex")

function splitLongSection(section) {
  if (section.text.length <= MAX_CHARS) return [section]
  const paragraphs = section.text.split(/\n\n+/).flatMap((paragraph) => {
    if (paragraph.length <= MAX_CHARS) return [paragraph]
    const pieces = []
    for (let offset = 0; offset < paragraph.length; offset += MAX_CHARS) {
      pieces.push(paragraph.slice(offset, offset + MAX_CHARS))
    }
    return pieces
  })
  const chunks = []
  let current = ""
  for (const paragraph of paragraphs) {
    if (current && current.length + paragraph.length + 2 > MAX_CHARS) {
      chunks.push(current)
      current = ""
    }
    current += `${current ? "\n\n" : ""}${paragraph}`
  }
  if (current) chunks.push(current)
  return chunks.map((text, index) => ({ ...section, locator: `${section.locator} · part ${index + 1}`, text }))
}

function sectionsFor(source) {
  const markdown = readFileSync(resolve(source.path), "utf8").replace(/\r\n/g, "\n").trim()
  const lines = markdown.split("\n")
  const sections = []
  let headings = []
  let body = []
  const flush = () => {
    const text = body.join("\n").trim()
    if (!text) return
    const locator = headings.at(-1) ?? source.title
    sections.push(...splitLongSection({ locator, text: `${headings.join(" > ")}\n\n${text}`.trim() }))
  }
  for (const line of lines) {
    const match = /^(#{1,4})\s+(.+)$/.exec(line)
    if (!match) {
      body.push(line)
      continue
    }
    flush()
    body = []
    const level = match[1].length
    const label = match[2].replace(/^\[([^\]]+)\]\([^)]*\)$/, "$1").trim()
    headings = [...headings.slice(0, level - 1), label]
  }
  flush()
  return sections.map((section, index) => {
    const key = `${source.id}:${hash(`${section.locator}:${index}`).slice(0, 20)}`
    return {
      key,
      sourceId: source.id,
      sourceTitle: source.title,
      sourceKind: source.kind,
      sourceUrl: source.url,
      locator: section.locator,
      contentHash: hash(section.text),
      text: section.text,
    }
  })
}

const chunks = SOURCES.flatMap(sectionsFor)
const output = `/** Generated by scripts/render-ask-ai-corpus.mjs. Do not edit by hand. */
export const AVANA_KNOWLEDGE_VERSION = "${hash(chunks.map((chunk) => chunk.contentHash).join(":"))}"

export const AVANA_KNOWLEDGE_CHUNKS = ${JSON.stringify(chunks, null, 2)} as const
`

if (process.argv.includes("--check")) {
  const current = readFileSync(resolve("convex/askAICorpus.generated.ts"), "utf8")
  if (current !== output) {
    process.stderr.write("Ask AI corpus is stale. Regenerate convex/askAICorpus.generated.ts.\n")
    process.exitCode = 1
  }
} else {
  process.stdout.write(output)
}
