export function translate(language: LanguageCode, key: string): string {
  const exact =
    ACTION_FLOW_TRANSLATIONS[language]?.[key] ??
    ACTION_TRANSLATIONS[language]?.[key] ??
    ONBOARDING_TRANSLATIONS[language]?.[key] ??
    SEARCH_TRANSLATIONS[language]?.[key] ??
    TRANSLATIONS[language]?.[key]
  if (exact) return exact

  const successfulMatch = key.match(/^(.+) successful$/)
  if (successfulMatch) {
    return `${translate(language, successfulMatch[1])} ${translate(language, "successful")}`
  }

  if (key.endsWith(" processed.")) {
    return `${key.slice(0, -" processed.".length)} ${translate(language, "processed")}.`
  }

  return key
}
